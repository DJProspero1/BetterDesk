# Render the same M/L/Q/Z paths into a multi-resolution Windows ICO locally.
Add-Type -AssemblyName System.Drawing
function Drawing-Path([string]$data) {
    $parts = $data -split ' '
    $path = [Drawing.Drawing2D.GraphicsPath]::new()
    [single]$x = 0; [single]$y = 0
    $i = 0
    while ($i -lt $parts.Length) {
        $command = $parts[$i++]; $letter = $command.Substring(0,1)
        if ($letter -eq 'Z') { $path.CloseFigure(); continue }
        [single]$a = $command.Substring(1); [single]$b = $parts[$i++]
        if ($letter -eq 'M') { $path.StartFigure(); $x=$a; $y=$b }
        elseif ($letter -eq 'L') { $path.AddLine($x,$y,$a,$b); $x=$a; $y=$b }
        elseif ($letter -eq 'Q') {
            [single]$endX=$parts[$i++]; [single]$endY=$parts[$i++]
            $path.AddBezier($x,$y,[single]($x+2*($a-$x)/3),[single]($y+2*($b-$y)/3),[single]($endX+2*($a-$endX)/3),[single]($endY+2*($b-$endY)/3),$endX,$endY)
            $x=$endX; $y=$endY
        } else { throw "Unsupported vector command $letter" }
    }
    return $path
}
$sizes = @(16,24,32,48,64,128,256)
$pngs = foreach ($size in $sizes) {
    $bitmap = [Drawing.Bitmap]::new($size,$size)
    $graphics = [Drawing.Graphics]::FromImage($bitmap)
    $graphics.SmoothingMode = [Drawing.Drawing2D.SmoothingMode]::AntiAlias
    $graphics.ScaleTransform($size/48.0,$size/48.0)
    $brush = [Drawing.SolidBrush]::new([Drawing.ColorTranslator]::FromHtml($design.background))
    $base = Drawing-Path $background
    $graphics.FillPath($brush,$base)
    $pen = [Drawing.Pen]::new([Drawing.ColorTranslator]::FromHtml($design.foreground),[single]2.5)
    $pen.StartCap = $pen.EndCap = [Drawing.Drawing2D.LineCap]::Round
    $pen.LineJoin = [Drawing.Drawing2D.LineJoin]::Round
    foreach ($data in $design.paths) { $path = Drawing-Path $data; $graphics.DrawPath($pen,$path); $path.Dispose() }
    $stream = [IO.MemoryStream]::new()
    $bitmap.Save($stream,[Drawing.Imaging.ImageFormat]::Png)
    ,$stream.ToArray()
    if ($size -eq 256) { $bitmap.Save((Join-Path $repoRoot 'assets/betterdesk.png'),[Drawing.Imaging.ImageFormat]::Png) }
    $stream.Dispose(); $pen.Dispose(); $base.Dispose(); $brush.Dispose(); $graphics.Dispose(); $bitmap.Dispose()
}
$icon = [IO.MemoryStream]::new(); $writer = [IO.BinaryWriter]::new($icon)
$writer.Write([uint16]0); $writer.Write([uint16]1); $writer.Write([uint16]$sizes.Length)
$offset = 6 + 16*$sizes.Length
for ($i=0; $i -lt $sizes.Length; $i++) {
    $dim = if ($sizes[$i] -eq 256) {0} else {$sizes[$i]}
    $writer.Write([byte]$dim); $writer.Write([byte]$dim); $writer.Write([uint16]0)
    $writer.Write([uint16]1); $writer.Write([uint16]32); $writer.Write([uint32]$pngs[$i].Length); $writer.Write([uint32]$offset)
    $offset += $pngs[$i].Length
}
foreach ($png in $pngs) { $writer.Write([byte[]]$png) }
[IO.File]::WriteAllBytes((Join-Path $repoRoot 'assets/betterdesk.ico'),$icon.ToArray())
$writer.Dispose(); $icon.Dispose()
